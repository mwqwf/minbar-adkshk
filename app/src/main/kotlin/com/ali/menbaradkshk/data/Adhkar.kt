/**
 * أذكار المسلم — بيانات محلّية بالكامل (تُصرَّف مع الحزمة، بلا أي شبكة).
 *
 * **منهج الاختيار:** الاقتصار على ما ثبت في الصحيحين أو صحّحه/حسّنه أهل العلم
 * في السنن، مع ذكر التخريج لكل ذكر. والاختصار مقصود: أهمّ الأذكار وأكثرها
 * عملاً لا استيعاب كل مرويّ — وبلا تكرار: ما اتّفق لفظه بين الصباح والمساء
 * يُكتب مرّة واحدة ويُشتقّ منه اللفظان (`ME` أدناه)، فلا يتضاعف النصّ ولا
 * يختلف بين الوقتين بالسهو.
 *
 * **لماذا في الكود لا في الشبكة؟** الصفحة يجب أن تعمل كاملةً دون إنترنت،
 * وحجم النصّ ضئيل (لا صور ولا صوت)، فلا مبرّر لتحميلها ولا لتخزينها.
 */

